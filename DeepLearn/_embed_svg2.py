def find_day_range(lines, day):
    """返回该 Day 的 (起始索引, 结束索引)"""
    st = None
    for i, l in enumerate(lines):
        if re.match(r'^## Day %d\b' % day, l):
            st = i
            break
    if st is None:
        return None, None
    en = len(lines)
    for i in range(st + 1, len(lines)):
        if lines[i].startswith('## '):
            en = i
            break
    return st, en


ok = fail = skip = 0
for (f, day, key, svg, alt, cap) in JOBS:
    if not os.path.exists(f):
        print('!! 文件不存在', f); fail += 1; continue
    s = io.open(f, encoding='utf-8').read()
    if svg in s:
        print('-- 已存在，跳过', os.path.basename(f), svg); skip += 1; continue
    lines = s.split('\n')
    st, en = find_day_range(lines, day)
    if st is None:
        print('!! 未找到 Day', day, f); fail += 1; continue
    # 在该 Day 内找目标 ### 标题
    tgt = None
    for i in range(st, en):
        if lines[i].startswith('### ') and key in lines[i]:
            tgt = i
            break
    if tgt is None:
        print('!! Day %d 内未找到 ### %s  (%s)' % (day, key, os.path.basename(f)))
        fail += 1
        continue
    # 落到该 ### 小节的末尾（下一个 ### 或 Day 结束之前）
    nxt = en
    for i in range(tgt + 1, en):
        if lines[i].startswith('### ') or lines[i].startswith('## '):
            nxt = i
            break
    # 回退掉小节末尾的空行
    ins = nxt
    while ins > tgt + 1 and lines[ins - 1].strip() == '':
        ins -= 1
    block = img_block(svg, alt, cap).strip('\n').split('\n')
    lines[ins:ins] = [''] + block + ['']
    io.open(f, 'w', encoding='utf-8').write('\n'.join(lines))
    print('OK', os.path.basename(f), 'Day', day, '| 插入于 L%d' % (ins + 1), '<=', svg)
    ok += 1

print()
print('成功 %d / 跳过 %d / 失败 %d （共 %d）' % (ok, skip, fail, len(JOBS)))
